def get_companies_by_niche(niche):
    """Filter companies by content niche"""
    matching = []
    niche_lower = niche.lower()
    
    for company_id, data in SAAS_DATABASE.items():
        if any(niche_lower in n.lower() for n in data["niches"]):
            matching.append(data)
    
    return matching


def format_for_claude_prompt():
    """Format database for Claude's system prompt"""
    formatted = []
    
    for company_id, data in SAAS_DATABASE.items():
        entry = f"""
**{data['name']}** - {data['category']}
Niches: {', '.join(data['niches'])}
- Ideal Customer: {data['ideal_creator']}
- Target Audience: {data['audience']}
- Pain Point: {data['pain_point']}
- Why Sponsor: {data['why_sponsor']}
- Pricing: {data['pricing_range']}
"""
        formatted.append(entry.strip())
    
    return "\n\n".join(formatted)
